package com.hackathon.agent.api.dto.response;

import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;

/**
 * DTO (Data Transfer Object) для вложения, прикреплённого к ответу бота.
 * <p>
 * Описывает один элемент из списка {@link ChatResponse#getAttachments()} и представляет
 * собой медиа-объект (изображение, документ или ссылку), который отображается
 * пользователю вместе с текстовым ответом бота.
 * </p>
 *
 * <p><b>Пример JSON-объекта вложения:</b></p>
 * <pre>
 * {
 *     "type": "complex_image",
 *     "url": "https://dsk.vrn.ru/upload/iblock/e65/plan.jpg",
 *     "title": "ЖК «Ласточкино»"
 * }
 * </pre>
 *
 * <p><b>Особенности:</b></p>
 * <ul>
 *     <li>Поле {@code type} определяет, как клиент должен интерпретировать вложение
 *         (например, отобразить как картинку, скачать как файл, показать как ссылку).</li>
 *     <li>Поле {@code url} должно быть валидной прямой ссылкой, доступной из клиента.
 *         Не рекомендуется использовать относительные пути без базового домена.</li>
 *     <li>Поле {@code title} служит для отображения подписи под вложением и не является
 *         обязательным с точки зрения клиента, но всегда заполняется бизнес-логикой.</li>
 * </ul>
 *
 * @author Axine
 * @since 1.0.0
 * @see ChatResponse#getAttachments()
 */
@Data
@NoArgsConstructor
@AllArgsConstructor
public class ChatAttachment {

    /**
     * Тип вложения.
     * <p>
     * Определяет способ отображения и обработки вложения на стороне клиента.
     * На текущий момент известные значения:
     * <ul>
     *     <li>{@code "complex_image"} — изображение жилого комплекса (рендер, фасад, территория).</li>
     * </ul>
     * </p>
     * <p>
     * Значение является строкой, а не перечислением, чтобы обеспечить расширяемость
     * без изменения контракта API. Клиент должен игнорировать неизвестные типы
     * вложений (например, не отображать их), не прерывая обработку ответа.
     * </p>
     */
    private String type;

    /**
     * Прямая ссылка на медиа-ресурс.
     * <p>
     * Абсолютный URL файла, доступный из клиента. Может указывать на внешний домен
     * (например, {@code https://dsk.vrn.ru/...}) или на статический ресурс
     * приложения (например, {@code /static/images/...}).
     * </p>
     * <p>
     * Клиент должен валидировать схему URL (обычно {@code http}/{@code https})
     * перед загрузкой.
     * </p>
     */
    private String url;

    /**
     * Подпись (title) вложения.
     * <p>
     * Отображается пользователю под вложением или рядом с ним. Обычно содержит
     * название жилого комплекса (например, {@code "ЖК «Ласточкино»"}), но может
     * быть любым осмысленным описанием.
     * </p>
     * <p>
     * Может быть {@code null} или пустой строкой, если подпись не требуется;
     * в этом случае клиент не должен отображать блок подписи.
     * </p>
     */
    private String title;
}
