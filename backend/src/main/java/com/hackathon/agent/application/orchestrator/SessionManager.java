package com.hackathon.agent.application.orchestrator;

import com.hackathon.agent.application.facade.ChatFacade;
import com.hackathon.agent.domain.model.Filters;
import com.hackathon.agent.domain.model.Session;
import com.hackathon.agent.infrastructure.ai.tools.GigaChatTools;

import java.util.List;

/**
 * Интерфейс менеджера сессий чат-бота.
 * <p>
 * Предоставляет операции для управления жизненным циклом, состоянием и историей
 * диалоговых сессий. Обеспечивает создание, получение, обновление, сохранение
 * и поиск сессий, а также управление контекстом текущей сессии в рамках потока
 * выполнения (ThreadLocal).
 * </p>
 *
 * <p><b>Основные обязанности:</b></p>
 * <ul>
 *     <li>Создание новой сессии или получение существующей по ключу.</li>
 *     <li>Сохранение состояния сессии (в памяти или в БД).</li>
 *     <li>Обновление фильтров и ранжированных списков (для рекомендательных систем).</li>
 *     <li>Ведение истории сообщений (добавление, хранение).</li>
 *     <li>Обновление временной метки последней активности.</li>
 *     <li>Поиск сессий, истёкших по времени неактивности (для автоматической очистки).</li>
 *     <li>Управление текущей сессией в контексте потока (для сквозной передачи данных
 *         между слоями приложения без явной передачи параметров).</li>
 * </ul>
 *
 * <p><b>Использование:</b></p>
 * Реализация интерфейса инжектируется в фасадные сервисы и сервисы оркестратора
 * ({@link ChatFacade}, {@link AgentOrchestrator}) для выполнения всех операций
 * с сессиями.
 *
 * @author Axine
 * @since 1.0.0
 * @see Session
 * @see ChatFacade
 * @see AgentOrchestrator
*/
public interface SessionManager {

    /**
     * Возвращает существующую сессию по ключу или создаёт новую, если она не найдена.
     * <p>
     * Если сессия с указанным {@code sessionKey} уже существует, она возвращается
     * без изменений. Если не существует — создаётся новая сессия с начальным статусом
     * (обычно {@code NEW} или {@code ACTIVE}), текущей временной меткой активности
     * и пустой историей сообщений.
     * </p>
     *
     * @param sessionKey уникальный строковый идентификатор сессии (обычно UUID в формате строки)
     * @return объект {@link Session}, либо существующий, либо вновь созданный
     * @throws IllegalArgumentException если {@code sessionKey} равен {@code null} или пуст
     */
    Session getOrCreate(String sessionKey);

    /**
     * Сохраняет текущее состояние сессии в хранилище (БД, кэш или in-memory).
     * <p>
     * Вызывается после любых изменений сессии (добавление сообщений, обновление статуса,
     * фильтров, ранжированных списков и т.д.) для гарантии сохранения данных.
     * </p>
     *
     * @param session объект сессии, который необходимо сохранить (не {@code null})
     * @throws IllegalArgumentException если {@code session} равен {@code null}
     * @throws RuntimeException если сохранение не удалось (например, ошибка БД)
     */
    void save(Session session);

    /**
     * Обновляет фильтры, связанные с сессией.
     * <p>
     * Фильтры используются для уточнения поиска или рекомендаций в рамках диалога.
     * Заменяет существующие фильтры переданными новыми.
     * </p>
     *
     * @param session    объект сессии (не {@code null})
     * @param newFilters новый объект фильтров (может быть {@code null}, что означает сброс фильтров)
     * @throws IllegalArgumentException если {@code session} равен {@code null}
     */
    void updateFilters(Session session, Filters newFilters);

    /**
     * Обновляет ранжированный список идентификаторов объектов (например, товаров или услуг),
     * связанных с сессией.
     * <p>
     * Используется для хранения промежуточных результатов ранжирования в процессе диалога.
     * Полностью заменяет предыдущий список новым.
     * </p>
     *
     * @param session   объект сессии (не {@code null})
     * @param rankedIds список идентификаторов в порядке ранжирования (может быть {@code null} или пустым)
     * @throws IllegalArgumentException если {@code session} равен {@code null}
     * @see #setRankedList(Session, List)
     */
    void updateRankedList(Session session, List<Long> rankedIds);

    /**
     * Добавляет новое сообщение в историю диалога сессии.
     * <p>
     * Сообщение сохраняется с указанием роли отправителя ({@code user} или {@code assistant})
     * и текстом. Обычно вызывается при получении каждого сообщения от пользователя и при
     * генерации ответа ассистента.
     * </p>
     *
     * @param session объект сессии (не {@code null})
     * @param role    роль отправителя: {@code "user"} или {@code "assistant"} (не {@code null}, не пусто)
     * @param text    текст сообщения (не {@code null}, но может быть пустым)
     * @throws IllegalArgumentException если {@code session}, {@code role} или {@code text} невалидны
     */
    void addMessage(Session session, String role, String text);

    /**
     * Обновляет временную метку последней активности сессии, устанавливая её на текущее время.
     * <p>
     * Вызывается при каждом взаимодействии с сессией (получении сообщения, обработке и т.д.)
     * для отслеживания неактивных сессий и их последующего завершения.
     * </p>
     *
     * @param session объект сессии (не {@code null})
     * @throws IllegalArgumentException если {@code session} равен {@code null}
     */
    void updateLastActivity(Session session);

    /**
     * Находит все сессии, время последней активности которых превышает заданный порог (в минутах).
     * <p>
     * Используется фоновыми заданиями (например, планировщиком) для очистки неактивных сессий
     * или перевода их в статус {@code EXPIRED}.
     * </p>
     *
     * @param timeoutMinutes максимально допустимое количество минут бездействия
     * @return список сессий, которые можно считать истёкшими (может быть пустым, но не {@code null})
     */
    List<Session> findExpired(int timeoutMinutes);

    /**
     * Возвращает текущую сессию, установленную в контексте потока.
     * <p>
     * Используется для доступа к сессии в глубоких слоях вызовов без необходимости
     * передавать её явно через цепочку методов.
     * </p>
     *
     * @return текущая сессия или {@code null}, если она не была установлена
     * @see #setCurrentSession(Session)
     * @see #clearCurrentSession()
     */
    Session getCurrentSession();

    /**
     * Устанавливает текущую сессию в контекст потока.
     * <p>
     * Обычно вызывается перед началом обработки запроса, чтобы все последующие
     * операции могли получить доступ к сессии через {@link #getCurrentSession()}.
     * </p>
     *
     * @param session сессия, которую нужно установить как текущую (может быть {@code null},
     *                что эквивалентно очистке)
     */
    void setCurrentSession(Session session);

    /**
     * Очищает текущую сессию из контекста потока.
     * <p>
     * Должна вызываться после завершения обработки запроса (например, в блоке {@code finally})
     * во избежание утечек памяти или использования некорректной сессии в других потоках.
     * </p>
     *
     * @see #setCurrentSession(Session)
     * @see #getCurrentSession()
     */
    void clearCurrentSession();

    /**
     * Устанавливает ранжированный список идентификаторов для сессии БЕЗ НЕМЕДЛЕННОГО СОХРАНЕНИЯ в БД.
     * <p>
     * В отличие от {@link #updateRankedList(Session, List)}, данный метод только изменяет
     * состояние объекта в памяти (сбрасывает индекс и обновляет время активности).
     * Используется внутри инструментов AI ({@link GigaChatTools}) для быстрой установки списка
     * перед возвратом ответа. Фактическое сохранение в базу данных должно быть выполнено
     * вызывающим кодом отдельно (через {@link #save(Session)}).
     * </p>
     *
     * @param session   объект сессии (не {@code null})
     * @param rankedIds список идентификаторов в порядке ранжирования (может быть {@code null} или пустым)
     * @throws IllegalArgumentException если {@code session} равен {@code null}
     * @see #updateRankedList(Session, List)
     */
    void setRankedList(Session session, List<Long> rankedIds);
}