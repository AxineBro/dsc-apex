package com.hackathon.agent.domain.exception;

/**
 * Базовое исключение доменного слоя приложения.
 * <p>
 * Является непроверяемым исключением (наследует {@link RuntimeException}), что позволяет
 * не декларировать его в сигнатурах методов. Предназначено для перенаправления бизнес-ошибок
 * из сервисного слоя (domain, business logic) на верхние уровни (контроллеры, обработчики).
 * </p>
 *
 * <p><b>Назначение:</b></p>
 * <ul>
 *     <li>Инкапсуляция ошибок предметной области (например, нарушение бизнес-правил,
 *         некорректное состояние сущности, недоступность ресурса).</li>
 *     <li>Обеспечение единого типа исключений для всех бизнес-ошибок, что упрощает
 *         глобальную обработку исключений (например, через {@code @ControllerAdvice}).</li>
 *     <li>Возможность дополнения иерархии специализированными исключениями-наследниками
 *         (например, {@code SessionExpiredException}, {@code ValidationException}).</li>
 * </ul>
 *
 * <p><b>Использование:</b></p>
 * <pre>
 * if (session.isExpired()) {
 *     throw new DomainException("Сессия истекла, пожалуйста, начните новую");
 * }
 *
 * // С вложенной причиной
 * try {
 *     saveSession(session);
 * } catch (DataAccessException e) {
 *     throw new DomainException("Не удалось сохранить сессию", e);
 * }
 * </pre>
 *
 * <p><b>Обработка:</b></p>
 * Рекомендуется перехватывать {@code DomainException} в глобальном обработчике исключений
 * и преобразовывать в HTTP-ответ с кодом 400 Bad Request (или другим подходящим кодом)
 * и понятным клиенту сообщением об ошибке.
 *
 * @author Axine
 * @since 1.0.0
 * @see org.springframework.web.bind.annotation.ControllerAdvice
 * @see jakarta.validation.ValidationException
 */
public class DomainException extends RuntimeException {

    /**
     * Создаёт исключение с указанным сообщением.
     * <p>
     * Используется для перенаправления бизнес-ошибки без дополнительной вложенной причины.
     * </p>
     *
     * @param message сообщение об ошибке, которое должно быть понятно разработчику,
     *                а также может быть показано пользователю после обработки
     */
    public DomainException(String message) {
        super(message);
    }

    /**
     * Создаёт исключение с указанным сообщением и причиной.
     * <p>
     * Рекомендуется использовать, когда ошибка доменного слоя является следствием
     * технического сбоя (например, ошибка БД, сбой внешнего сервиса) — это сохраняет
     * стек вызовов для диагностики.
     * </p>
     *
     * @param message сообщение об ошибке
     * @param cause   вложенная причина (исключение, вызвавшее данную ошибку)
     */
    public DomainException(String message, Throwable cause) {
        super(message, cause);
    }
}