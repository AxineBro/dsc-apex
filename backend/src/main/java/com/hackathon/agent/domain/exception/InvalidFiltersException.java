package com.hackathon.agent.domain.exception;

/**
 * Исключение, выбрасываемое при обнаружении некорректных или невалидных фильтров
 * в процессе поиска, подбора или рекомендации объектов (например, квартир).
 * <p>
 * Является частным случаем {@link DomainException} и используется для сигнализации
 * о том, что переданные клиентом или сгенерированные системой фильтры не соответствуют
 * требованиям (недопустимые значения, конфликтующие параметры, отсутствие обязательных
 * полей и т.д.).
 * </p>
 *
 * <p><b>Назначение:</b></p>
 * <ul>
 *     <li>Инкапсуляция ошибок, связанных с валидацией фильтров на уровне бизнес-логики
 *         (помимо аннотаций {@code @Valid}, которые проверяют только структуру, но не
 *         семантическую корректность).</li>
 *     <li>Предоставление гибкого механизма для передачи детализированного сообщения
 *         об ошибке, которое может быть показано пользователю.</li>
 *     <li>Упрощение отладки и мониторинга за счёт явного указания причины ошибки.</li>
 * </ul>
 *
 * <p><b>Типичные сценарии использования:</b></p>
 * <pre>
 * // Проверка диапазона цен
 * if (filters.getMinPrice() != null && filters.getMaxPrice() != null
 *         && filters.getMinPrice() > filters.getMaxPrice()) {
 *     throw new InvalidFiltersException("Минимальная цена не может быть больше максимальной");
 * }
 *
 * // Проверка обязательных параметров
 * if (filters.getCity() == null || filters.getCity().isBlank()) {
 *     throw new InvalidFiltersException("Город должен быть указан для поиска");
 * }
 * </pre>
 *
 * <p><b>Обработка на уровне контроллера:</b></p>
 * Рекомендуется перехватывать данное исключение в глобальном обработчике
 * и возвращать клиенту HTTP-статус {@code 400 Bad Request} с телом ответа,
 * содержащим сообщение об ошибке. Это даст клиенту возможность исправить
 * параметры запроса.
 *
 * <p><b>Отличие от валидации через {@code @Valid}:</b></p>
 * Аннотации {@code @NotNull}, {@code @Min}, {@code @Max} проверяют структуру полей,
 * но не могут проверить логические связи между полями (например, диапазон дат,
 * взаимное исключение параметров). Данное исключение служит именно для таких случаев.
 *
 * @author Axine
 * @since 1.0.0
 * @see DomainException
 * @see jakarta.validation.Valid
 */
public class InvalidFiltersException extends DomainException {

    /**
     * Создаёт исключение с указанным сообщением об ошибке.
     * <p>
     * Сообщение должно содержать понятное описание того, что именно не так
     * с фильтрами, чтобы клиент мог исправить запрос.
     * </p>
     *
     * @param message детализированное сообщение об ошибке (не {@code null}, не пустое)
     */
    public InvalidFiltersException(String message) {
        super(message);
    }
}