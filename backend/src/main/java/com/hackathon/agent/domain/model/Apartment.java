package com.hackathon.agent.domain.model;

import java.math.BigDecimal;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

/**
 * Модель данных, представляющая информацию о квартире из внешней ERP-системы.
 * <p>
 * Содержит полные характеристики жилого объекта, включая адрес, площадь, цену,
 * этажность, количество комнат, статус, вид из окон и наличие парковки.
 * Данные получены через интеграцию с ERP-системой по API (JSON-формат).
 * </p>
 *
 * <p><b>Источник данных:</b></p>
 * Объекты данного класса формируются на основе ответов внешнего API
 * (ERP-система застройщика) и используются в бизнес-логике для поиска,
 * подбора, ранжирования и бронирования квартир.
 *
 * <p><b>Использование:</b></p>
 * <ul>
 *     <li>Сериализация/десериализация JSON для обмена с фронтендом и внешними системами.</li>
 *     <li>Хранение в кэше и репозиториях для оперативного доступа.</li>
 *     <li>Взаимодействие с модулями фильтрации, ранжирования и бронирования.</li>
 * </ul>
 *
 * <p><b>Примечания по полям:</b></p>
 * <ul>
 *     <li>Поле {@code status} может принимать значения: {@code AVAILABLE}, {@code BOOKED},
 *         {@code SOLD}, {@code RESERVED} (определяется бизнес-логикой ERP).</li>
 *     <li>Поле {@code viewType} описывает вид из окон (например, {@code PARK}, {@code CITY},
 *         {@code WATER}, {@code YARD}).</li>
 *     <li>Поле {@code parking} указывает на наличие парковочного места (true/false).</li>
 * </ul>
 *
 * <p><b>Пример JSON-объекта:</b></p>
 * <pre>
 * {
 *     "id": 1001,
 *     "complexName": "ЖК Золотые купола",
 *     "address": "ул. Ленина, д. 15, кв. 42",
 *     "area": 58.5,
 *     "price": 12500000.00,
 *     "floor": 8,
 *     "totalFloors": 25,
 *     "rooms": 2,
 *     "status": "AVAILABLE",
 *     "viewType": "PARK",
 *     "parking": true
 * }
 * </pre>
 *
 * @author Axine
 * @since 1.0.0
 * @see com.fasterxml.jackson.databind.ObjectMapper
 */
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class Apartment {

    /**
     * Уникальный идентификатор квартиры в ERP-системе.
     * <p>
     * Первичный ключ объекта, используемый для ссылок на квартиру
     * в операциях поиска, бронирования и логирования.
     * </p>
     */
    private Long id;

    /**
     * Внешний идентификатор квартиры.
     * <p>
     * Используется для связи с данными из внешних источников (например, сайта застройщика).
     * Может содержать уникальный код, присвоенный вне ERP-системы.
     * </p>
     */
    private String externalId;

    /**
     * Номер квартиры.
     * <p>
     * Строковое значение, может содержать буквенные обозначения (например, "140А").
     * Используется для идентификации квартиры на этаже и в документации.
     * </p>
     */
    private String flatNumber;

    /**
     * Позиция дома (корпуса) в жилом комплексе.
     * <p>
     * Например, "Позиция 35 мкр 2". Указывает на конкретный строящийся объект
     * внутри комплекса. Используется для группировки и фильтрации.
     * </p>
     */
    private String housePosition;

    /**
     * Название жилого комплекса (застройки), к которому относится квартира.
     * <p>
     * Строковое значение, может содержать маркетинговое наименование.
     * Используется для группировки и отображения в интерфейсе.
     * </p>
     */
    private String complexName;

    /**
     * Район города, в котором расположен жилой комплекс.
     * <p>
     * Строковое значение, например, "Советский". Используется для фильтрации
     * и отображения местоположения.
     * </p>
     */
    private String district;

    /**
     * Полный почтовый адрес квартиры (город, улица, дом, квартира).
     * <p>
     * Строковое значение, используется для точной идентификации местоположения
     * и отображения на картах или в списке результатов.
     * </p>
     */
    private String address;

    /**
     * Общая площадь квартиры в квадратных метрах.
     * <p>
     * Числовое значение с плавающей точкой (BigDecimal для точности).
     * Используется в фильтрах (диапазон площади) и расчётах стоимости.
     * </p>
     */
    private BigDecimal area;

    /**
     * Жилая площадь квартиры в квадратных метрах.
     * <p>
     * Числовое значение с плавающей точкой (BigDecimal для точности).
     * Отличается от общей площади и используется в расчётах и фильтрах.
     * </p>
     */
    private BigDecimal livingArea;

    /**
     * Стоимость квартиры в рублях.
     * <p>
     * Числовое значение с плавающей точкой (BigDecimal для точности валютных расчётов).
     * Используется в фильтрах по бюджету и при отображении цены.
     * </p>
     */
    private BigDecimal price;

    /**
     * Цена за квадратный метр площади квартиры в рублях.
     * <p>
     * Числовое значение с плавающей точкой (BigDecimal для точности).
     * Вычисляется как отношение общей стоимости к общей площади.
     * Используется для сравнения предложений и в фильтрах.
     * </p>
     */
    private BigDecimal pricePerM2;


    /**
     * Этаж, на котором расположена квартира.
     * <p>
     * Целочисленное значение, начиная с 1 (первый этаж).
     * Используется в фильтрах (этажность) и при ранжировании предложений.
     * </p>
     */
    private Integer floor;

    /**
     * Общее количество этажей в доме (корпусе).
     * <p>
     * Целочисленное значение, используется для расчёта коэффициентов
     * (например, вида из окон, тишины) и в фильтрах по типу дома.
     * </p>
     */
    private Integer totalFloors;

    /**
     * Количество комнат в квартире.
     * <p>
     * Целочисленное значение (1, 2, 3 и т.д.). Является ключевым фильтром
     * при поиске подходящих вариантов для клиента.
     * </p>
     */
    private Integer rooms;

    /**
     * Признак студии.
     * <p>
     * Булево значение: {@code true} — квартира является студией,
     * {@code false} — обычная квартира. Учитывается в фильтрах.
     * </p>
     */
    private Boolean studio;

    /**
     * Текущий статус квартиры в ERP-системе.
     * <p>
     * Возможные значения (определены бизнес-логикой):
     * <ul>
     *     <li>{@code свободна} — доступна для бронирования и покупки.</li>
     *     <li>{@code забронирована} — забронирована (в процессе оформления).</li>
     *     <li>{@code продана} — продана, недоступна.</li>
     * </ul>
     * Статус определяет, может ли объект участвовать в подборе.
     * </p>
     */
    private String status;

    /**
     * Тип вида из окон (панорама).
     * <p>
     * Описывает, что видно из окон квартиры. Возможные значения:
     * <ul>
     *     <li>{@code park} — парк или зелёная зона.</li>
     *     <li>{@code city} — городской пейзаж (дома, улицы).</li>
     *     <li>{@code river} — водоём (река, озеро, пруд).</li>
     *     <li>{@code yard} — внутренний двор.</li>
     * </ul>
     * Используется как дополнительный критерий при выборе.
     * </p>
     */
    private String viewType;

    /**
     * Наличие парковочного места (машино-места) у квартиры.
     * <p>
     * Булево значение: {@code true} — парковка присутствует,
     * {@code false} — отсутствует. Учитывается в фильтрах и при ранжировании.
     * </p>
     */
    private Boolean parking;

    /**
     * Планируемый срок сдачи дома (корпуса) в эксплуатацию.
     * <p>
     * Строковое значение, например, "декабрь 2026". Используется для информирования
     * клиентов и в фильтрах по сроку сдачи.
     * </p>
     */
    private String deadline;

    /**
     * URL-адрес страницы квартиры с подробной информацией.
     * <p>
     * Ссылка на карточку квартиры на сайте застройщика или в системе.
     * Используется для перехода к деталям.
     * </p>
     */
    private String cardUrl;

    /**
     * URL-адрес изображения планировки квартиры.
     * <p>
     * Ссылка на файл с планировкой (обычно в формате JPEG или PNG).
     * Используется для визуального отображения.
     * </p>
     */
    private String planUrl;
}