package com.hackathon.agent.domain.exception;

/**
 * Исключение, выбрасываемое при отсутствии результатов поиска квартир
 * по заданным критериям (фильтрам, запросу пользователя и т.д.).
 * <p>
 * Является частным случаем {@link DomainException} и используется в бизнес-логике
 * для сигнализации о том, что ни одна квартира не соответствует условиям поиска.
 * </p>
 *
 * <p><b>Назначение:</b></p>
 * <ul>
 *     <li>Инкапсуляция ошибки "квартиры не найдены" на уровне домена.</li>
 *     <li>Предоставление гибкого механизма для передачи детализированного сообщения
 *         о причине отсутствия результатов (например, слишком жёсткие фильтры,
 *         некорректные параметры, отсутствие подходящих вариантов в БД).</li>
 *     <li>Упрощение обработки ошибок в сервисном слое и контроллерах за счёт
 *         использования иерархии исключений.</li>
 * </ul>
 *
 * <p><b>Типичные сценарии использования:</b></p>
 * <pre>
 * // В сервисе поиска квартир
 * List&lt;Apartment&gt; results = apartmentRepository.findByFilters(filters);
 * if (results.isEmpty()) {
 *     throw new NoApartmentsFoundException("По вашему запросу квартир не найдено. Попробуйте изменить параметры поиска.");
 * }
 * return results;
 *
 * // С детализацией
 * throw new NoApartmentsFoundException(
 *     String.format("В городе %s с бюджетом до %,d руб. квартир не найдено", city, budget)
 * );
 * </pre>
 *
 * <p><b>Обработка на уровне контроллера:</b></p>
 * Рекомендуется перехватывать данное исключение в глобальном обработчике
 * (например, {@code @ControllerAdvice}) и возвращать клиенту HTTP-статус
 * {@code 404 Not Found} с телом ответа, содержащим сообщение об ошибке.
 * Альтернативно можно вернуть статус {@code 204 No Content} или {@code 200 OK}
 * с пустым списком, если клиент ожидает пустой результат, а не ошибку.
 *
 * <p><b>Отличие от {@link ApartmentNotFoundException}:</b></p>
 * <ul>
 *     <li>{@link ApartmentNotFoundException} — для случая, когда запрошена
 *         конкретная квартира по ID, но она не существует.</li>
 *     <li>{@code NoApartmentsFoundException} — когда выполнялся поиск по критериям,
 *         но ни одна квартира не подошла.</li>
 * </ul>
 *
 * @author Axine
 * @since 1.0.0
 * @see DomainException
 * @see ApartmentNotFoundException
 */
public class NoApartmentsFoundException extends DomainException {

    /**
     * Создаёт исключение с указанным сообщением об ошибке.
     * <p>
     * Сообщение должно содержать понятное описание причины отсутствия результатов,
     * чтобы клиент мог скорректировать запрос или получить обратную связь.
     * </p>
     *
     * @param message детализированное сообщение об ошибке (не {@code null}, не пустое)
     */
    public NoApartmentsFoundException(String message) {
        super(message);
    }
}