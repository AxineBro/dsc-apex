package com.hackathon.agent.domain.model;

import lombok.Getter;

/**
 * Перечисление, определяющее возможные статусы коммерческого предложения.
 * <p>
 * Управляет жизненным циклом оффера: от создания до генерации PDF или
 * признания предложения неактуальным. Статус изменяется при создании
 * коммерческого предложения, успешной генерации PDF, отказе клиента,
 * бронировании квартиры или истечении срока действия.
 * </p>
 *
 * <p><b>Жизненный цикл оффера:</b></p>
 * <ol>
 *     <li>{@link #NEW} — оффер создан, PDF ещё не готов.</li>
 *     <li>{@link #READY} — PDF сгенерирован и доступен для скачивания.</li>
 *     <li>{@link #EXPIRED} — оффер устарел (например, квартира забронирована,
 *         клиент отказался или истёк срок действия).</li>
 * </ol>
 *
 * <p><b>Использование в коде:</b></p>
 * <pre>
 * Offer offer = offerService.create(...);
 * if (offer.getStatus() == OfferStatus.READY) {
 *     // PDF доступен для скачивания или отправки клиенту
 *     return offer.getPdfUrl();
 * }
 *
 * // Установка статуса
 * offer.setStatus(OfferStatus.EXPIRED);
 *
 * // Преобразование в строковый код
 * String code = offer.getStatus().getCode();
 *
 * // Восстановление из кода
 * OfferStatus status = OfferStatus.fromCode("READY");
 * </pre>
 *
 * <p><b>Связь с другими классами:</b></p>
 * <ul>
 *     <li>Используется в {@code Offer} для хранения текущего статуса предложения.</li>
 *     <li>Проверяется в сервисах генерации PDF и выдачи оффера, чтобы не отдавать
 *         клиенту неготовый или устаревший документ.</li>
 *     <li>Может передаваться через API в виде строкового кода {@code getCode()}.</li>
 * </ul>
 *
 * @author Axine
 * @since 1.0.0
 */
@Getter
public enum OfferStatus {

    /**
     * Статус "новый".
     * <p>
     * Присваивается при создании коммерческого предложения. PDF-документ ещё
     * не сформирован, поэтому скачивание или отправка клиенту недоступны.
     * Обычно из этого состояния оффер переходит в {@link #READY} после
     * успешной генерации PDF.
     * </p>
     */
    NEW("NEW"),

    /**
     * Статус "готов".
     * <p>
     * PDF-документ успешно сгенерирован и доступен для скачивания или отправки.
     * Это активное состояние оффера, в котором он может быть использован
     * в диалоге с клиентом или передан менеджеру.
     * </p>
     */
    READY("READY"),

    /**
     * Статус "истёк".
     * <p>
     * Устанавливается, когда оффер потерял актуальность: квартира забронирована,
     * клиент отказался, истёк срок действия или предложение заменено новым.
     * В этом состоянии PDF может оставаться доступным для истории, но
     * использовать оффер как актуальное предложение нельзя.
     * </p>
     */
    EXPIRED("EXPIRED");

    /**
     * Строковый код статуса, используемый для сериализации и передачи по API.
     * <p>
     * Значения: {@code "NEW"}, {@code "READY"}, {@code "EXPIRED"}.
     * </p>
     */
    private final String code;

    /**
     * Конструктор для создания статуса с кодом.
     *
     * @param code строковое представление статуса (не {@code null}, не пусто)
     */
    OfferStatus(String code) {
        this.code = code;
    }

    /**
     * Преобразует строковый код в соответствующее значение перечисления.
     * <p>
     * Используется для десериализации из JSON или при получении из внешних систем.
     * </p>
     *
     * @param code строковый код статуса (не {@code null})
     * @return соответствующее значение {@link OfferStatus}
     * @throws IllegalArgumentException если код не соответствует ни одному из статусов
     */
    public static OfferStatus fromCode(String code) {
        for (OfferStatus s : values()) {
            if (s.code.equals(code)) return s;
        }
        throw new IllegalArgumentException("Unknown offer status: " + code);
    }

    /**
     * Возвращает строковое представление статуса (его код).
     * <p>
     * Переопределён для удобства логирования и вывода.
     * </p>
     *
     * @return код статуса
     */
    @Override
    public String toString() {
        return code;
    }
}