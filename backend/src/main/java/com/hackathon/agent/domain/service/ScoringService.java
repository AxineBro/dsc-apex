package com.hackathon.agent.domain.service;

import com.hackathon.agent.application.orchestrator.SessionManager;
import com.hackathon.agent.domain.model.Apartment;
import com.hackathon.agent.domain.model.ScoredApartment;

import java.util.List;

/**
 * Сервис для оценки квартир по неметрическим параметрам (качественным характеристикам).
 * <p>
 * Выполняет расчёт скора (числовой оценки) для каждой квартиры из переданного списка
 * на основе таких критериев, как вид из окон, наличие парковки, этаж, тип дома,
 * близость к метро, инфраструктура и другие неметрические факторы, которые не являются
 * строгими числовыми фильтрами, но влияют на привлекательность объекта для клиента.
 * </p>
 *
 * <p><b>Назначение:</b></p>
 * <ul>
 *     <li>Ранжирование квартир по качественным параметрам для формирования
 *         списка рекомендаций, отсортированных по убыванию приоритета.</li>
 *     <li>Интеграция с алгоритмами машинного обучения или экспертными правилами
 *         для вычисления комплексной оценки.</li>
 *     <li>Преобразование списка идентификаторов квартир в список {@link ScoredApartment},
 *         содержащий как саму квартиру, так и вычисленный скор.</li>
 * </ul>
 *
 * <p><b>Критерии оценки (примеры):</b></p>
 * <ul>
 *     <li><b>Вид из окон:</b> на парк, на воду, на город — выше оценка, чем во двор.</li>
 *     <li><b>Наличие парковки:</b> наличие повышает скор.</li>
 *     <li><b>Этаж:</b> золотая середина (не первый, не последний) оценивается выше.</li>
 *     <li><b>Тип дома:</b> монолит/кирпич выше, чем панель.</li>
 *     <li><b>Близость к метро:</b> чем ближе, тем выше балл.</li>
 *     <li><b>Состояние отделки:</b> чистая отделка выше, чем без отделки.</li>
 * </ul>
 *
 * <p><b>Использование:</b></p>
 * <pre>
 * ScoringService scoringService = ...;
 *
 * // Получаем список ID квартир после фильтрации
 * List&lt;Long&gt; ids = apartments.stream().map(Apartment::getId).collect(Collectors.toList());
 *
 * // Оценка неметрических параметров
 * List&lt;ScoredApartment&gt; scored = scoringService.rateApartments(ids);
 *
 * // Сортировка по убыванию скора
 * scored.sort(Comparator.comparing(ScoredApartment::getScore).reversed());
 *
 * // Возврат клиенту лучших вариантов
 * List&lt;Apartment&gt; top = scored.stream()
 *         .limit(10)
 *         .map(ScoredApartment::getApartment)
 *         .collect(Collectors.toList());
 * </pre>
 *
 * <p><b>Особенности реализации:</b></p>
 * <ul>
 *     <li>Скор может вычисляться как взвешенная сумма баллов по каждому критерию.</li>
 *     <li>Веса критериев могут настраиваться через конфигурацию или зависеть от типа клиента.</li>
 *     <li>При отсутствии данных по какому-либо параметру используется нейтральное или дефолтное значение.</li>
 * </ul>
 *
 * <p><b>Обработка ошибок:</b></p>
 * Если передан пустой список или {@code null}, метод должен вернуть пустой список
 * (не {@code null}). Если какой-либо ID не найден в системе, соответствующая квартира
 * может быть исключена из результата или оценена с минимальным скором — зависит от реализации.
 *
 * @author Axine
 * @since 1.0.0
 * @see ScoredApartment
 * @see Apartment
 * @see SessionManager#setRankedList
 */
public interface ScoringService {

    /**
     * Вычисляет оценки (скоры) для списка квартир по неметрическим параметрам.
     * <p>
     * Для каждого идентификатора квартиры из переданного списка выполняется расчёт
     * числового скора на основе качественных характеристик объекта. Возвращается
     * список объектов {@link ScoredApartment}, содержащих как саму квартиру, так и
     * вычисленную оценку.
     * </p>
     *
     * <p><b>Алгоритм оценки (зависит от реализации):</b></p>
     * <ol>
     *     <li>Получение полной информации о квартире по ID (через {@link ApartmentSearchService}).</li>
     *     <li>Оценка каждого неметрического параметра по шкале, например, от 0 до 10.</li>
     *     <li>Применение весовых коэффициентов для каждого параметра.</li>
     *     <li>Суммирование взвешенных оценок в итоговый скор (часто нормируется к диапазону 0–100).</li>
     * </ol>
     *
     * <p><b>Пример вычисления:</b></p>
     * <pre>
     * // Допустим, используются веса:
     * // вид — 30%, парковка — 20%, этаж — 20%, близость к метро — 30%
     * int score = (viewScore * 0.3) + (parkingScore * 0.2) + (floorScore * 0.2) + (metroScore * 0.3);
     * </pre>
     *
     * <p><b>Возвращаемое значение:</b></p>
     * Список {@link ScoredApartment} в том же порядке, что и входной список ID,
     * либо отсортированный по убыванию скора — зависит от реализации.
     * Рекомендуется сохранять порядок входного списка, чтобы вызывающий код мог
     * сам управлять сортировкой.
     *
     * <p><b>Обработка отсутствующих квартир:</b></p>
     * Если квартира с указанным ID не найдена, она исключается из результата
     * (без выбрасывания исключения), так как оценка невозможна. В лог может быть
     * записано предупреждение.
     *
     * @param apartmentIds список идентификаторов квартир для оценки (может быть {@code null} или пустым)
     * @return список {@link ScoredApartment} с вычисленными скорами (не {@code null}, может быть пустым)
     * @throws IllegalArgumentException если список содержит {@code null} элементы
     * @throws RuntimeException если произошла ошибка при получении данных о квартирах
     *         (например, ошибка соединения с ERP)
     */
    List<ScoredApartment> rateApartments(List<Long> apartmentIds);
}