package com.hackathon.agent.domain.exception;

/**
 * Исключение, выбрасываемое при превышении максимально допустимого количества циклов подбора
 * в процессе обработки запроса.
 * <p>
 * Является частным случаем {@link DomainException} и сигнализирует о том, что система
 * достигла лимита итераций при выполнении сложного алгоритма (например, многократные вызовы
 * AI-модели для уточнения или подбора вариантов, циклические запросы к внешним сервисам).
 * </p>
 *
 * <p><b>Назначение:</b></p>
 * <ul>
 *     <li>Защита системы от бесконечных циклов или чрезмерного количества итераций,
 *         которые могут привести к деградации производительности или неограниченному
 *         потреблению ресурсов (например, токенов AI-модели).</li>
 *     <li>Обеспечение контролируемого завершения алгоритма с информированием клиента
 *         о необходимости изменить параметры запроса или повторить попытку позже.</li>
 *     <li>Упрощение отладки и мониторинга за счёт явного указания причины сбоя.</li>
 * </ul>
 *
 * <p><b>Типичный сценарий использования:</b></p>
 * <pre>
 * // В цикле обработки запросов к GigaChat
 * int cycles = 0;
 * while (cycles < MAX_CYCLES) {
 *     // Выполнение шага алгоритма
 *     cycles++;
 *     if (cycles >= MAX_CYCLES) {
 *         throw new CycleLimitExceededException(MAX_CYCLES);
 *     }
 * }
 * </pre>
 *
 * <p><b>Обработка на уровне контроллера:</b></p>
 * Рекомендуется перехватывать данное исключение в глобальном обработчике
 * и возвращать клиенту HTTP-статус {@code 400 Bad Request} или {@code 429 Too Many Requests}
 * с телом ответа, содержащим сообщение об ошибке. Это позволит клиенту понять,
 * что запрос слишком сложен или требует корректировки.
 *
 * <p><b>Связь с параметрами конфигурации:</b></p>
 * Максимальное количество циклов обычно задаётся через внешнюю конфигурацию
 * (например, {@code app.max.cycles}), что позволяет адаптировать лимит под разные
 * сценарии без изменения кода.
 *
 * @author Axine
 * @since 1.0.0
 * @see DomainException
 */
public class CycleLimitExceededException extends DomainException {

    /**
     * Создаёт исключение при превышении допустимого числа циклов подбора.
     * <p>
     * Формирует сообщение вида:
     * {@code "Превышен лимит циклов подбора (максимум <maxCycles>)"},
     * где {@code maxCycles} — установленное максимальное значение.
     * </p>
     * <p>
     * Данное исключение обычно выбрасывается при достижении верхней границы
     * итераций, чтобы предотвратить зависание или бесконечную обработку.
     * </p>
     *
     * @param maxCycles максимальное допустимое количество циклов,
     *                  которое было превышено
     */
    public CycleLimitExceededException(int maxCycles) {
        super("Превышен лимит циклов подбора (максимум " + maxCycles + ")");
    }
}