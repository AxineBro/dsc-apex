package com.hackathon.agent.domain.service;

import com.hackathon.agent.domain.exception.DomainException;
import com.hackathon.agent.domain.model.Apartment;
import com.hackathon.agent.domain.model.Session;
import com.hackathon.agent.domain.model.SessionState;

/**
 * Сервис для генерации коммерческого предложения на основе выбранной квартиры и данных сессии.
 * <p>
 * Создаёт текстовое или структурированное коммерческое предложение (оферту) для клиента,
 * которое включает информацию о квартире, условия покупки, контактные данные менеджера
 * и другие релевантные детали. Предложение может быть отправлено клиенту в чате,
 * по электронной почте или использовано для печатной версии.
 * </p>
 *
 * <p><b>Назначение:</b></p>
 * <ul>
 *     <li>Формирование персонализированного оффера на основе выбранной квартиры
 *         и предпочтений клиента, собранных в ходе диалога.</li>
 *     <li>Интеграция с шаблонизаторами (например, Thymeleaf, FreeMarker) для создания
 *         структурированных документов (PDF, HTML, текстовые сообщения).</li>
 *     <li>Включение в оффер информации о ценах, площади, адресе, фотографиях,
 *         условиях кредитования, планировке и других параметрах.</li>
 * </ul>
 *
 * <p><b>Использование:</b></p>
 * <pre>
 * OfferGeneratorService offerService = ...;
 *
 * // Генерация оффера для выбранной квартиры
 * Apartment selected = apartmentSearchService.getById(1001L);
 * String offer = offerService.generateOffer(selected, session);
 *
 * // Отправка клиенту
 * sessionManager.addMessage(session, "assistant", offer);
 * session.setStatus(SessionState.OFFER_READY);
 * sessionManager.save(session);
 * </pre>
 *
 * <p><b>Содержание оффера (пример):</b></p>
 * <ul>
 *     <li>Название ЖК и адрес квартиры.</li>
 *     <li>Характеристики: площадь, количество комнат, этаж, этажность дома.</li>
 *     <li>Стоимость, возможные скидки или специальные условия.</li>
 *     <li>Данные для связи с менеджером.</li>
 *     <li>Предложение о бронировании и дальнейшие шаги.</li>
 * </ul>
 *
 * <p><b>Обработка ошибок:</b></p>
 * Если генерация оффера невозможна (например, недостаточно данных о квартире),
 * сервис может выбрасывать {@link DomainException} с соответствующим сообщением.
 * Также возможна генерация упрощённого варианта при отсутствии части данных.
 *
 * @author Axine
 * @since 1.0.0
 * @see Apartment
 * @see Session
 * @see SessionState#OFFER_READY
 */
public interface OfferGeneratorService {

    /**
     * Генерирует коммерческое предложение для указанной квартиры и сессии.
     * <p>
     * Создаёт текст оффера, который содержит полную информацию о квартире,
     * а также учитывает историю диалога и предпочтения клиента (например,
     * желаемый бюджет, площадь, комнаты). Возвращаемая строка может быть
     * в формате HTML, Markdown или plain text — зависит от реализации.
     * </p>
     *
     * <p><b>Параметры:</b></p>
     * <ul>
     *     <li>{@code apartment} — выбранная квартира. Не {@code null}.
     *         Содержит все характеристики объекта.</li>
     *     <li>{@code session} — сессия клиента. Не {@code null}.
     *         Используется для извлечения истории диалога, фильтров, контактных данных.</li>
     * </ul>
     *
     * <p><b>Возвращаемое значение:</b></p>
     * Строка с текстом коммерческого предложения. Может быть многострочной,
     * содержать форматирование (например, Markdown для чата).
     *
     * <p><b>Исключения:</b></p>
     * <ul>
     *     <li>{@link IllegalArgumentException} — если любой из аргументов равен {@code null}.</li>
     *     <li>{@link DomainException} — если невозможно сгенерировать оффер
     *         (например, отсутствуют обязательные данные в сессии или квартире).</li>
     * </ul>
     *
     * @param apartment выбранная квартира (не {@code null})
     * @param session   сессия клиента (не {@code null})
     * @return сгенерированное коммерческое предложение в виде строки
     * @throws IllegalArgumentException если {@code apartment} или {@code session} равны {@code null}
     * @throws DomainException         если генерация оффера невозможна
     */
    String generateOffer(Apartment apartment, Session session);
}