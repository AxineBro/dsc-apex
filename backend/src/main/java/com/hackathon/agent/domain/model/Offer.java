package com.hackathon.agent.domain.model;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.time.LocalDateTime;
import java.util.UUID;

/**
 * Доменная модель коммерческого предложения (КП).
 * <p>
 * Содержит снимок данных, на основании которых было построено КП,
 * а также сгенерированный PDF-файл в виде байтового массива.
 * </p>
 *
 * <p><b>Назначение:</b></p>
 * <ul>
 *     <li>Хранение всех атрибутов коммерческого предложения, сформированного
 *         в рамках диалоговой сессии.</li>
 *     <li>Предоставление данных для генерации PDF-документа и его последующей
 *         выдачи клиенту или передачи менеджеру.</li>
 *     <li>Сериализация и десериализация в JSON для обмена между слоями
 *         приложения и внешними системами.</li>
 * </ul>
 *
 * <p><b>Жизненный цикл:</b></p>
 * <ol>
 *     <li>Создание объекта с заполненными полями {@code id}, {@code sessionId},
 *         {@code apartmentId}, {@code offerText} и {@code createdAt}.
 *         Статус устанавливается в {@link OfferStatus#NEW}.</li>
 *     <li>Генерация PDF-файла и заполнение поля {@code pdfData}.
 *         Статус изменяется на {@link OfferStatus#READY}.</li>
 *     <li>При потере актуальности (бронь квартиры, отказ клиента, истечение срока)
 *         статус переводится в {@link OfferStatus#EXPIRED}.</li>
 * </ol>
 *
 * <p><b>Использование:</b></p>
 * <pre>
 * // Создание нового оффера
 * Offer offer = Offer.builder()
 *         .id(UUID.randomUUID())
 *         .sessionId(session.getId())
 *         .apartmentId(apartment.getId())
 *         .offerText(offerText)
 *         .createdAt(LocalDateTime.now())
 *         .status(OfferStatus.NEW)
 *         .build();
 *
 * // После генерации PDF
 * offer.setPdfData(pdfBytes);
 * offer.setStatus(OfferStatus.READY);
 *
 * // Проверка готовности
 * if (offer.getStatus() == OfferStatus.READY) {
 *     return offer.getPdfData();
 * }
 * </pre>
 *
 * <p><b>Связь с другими классами:</b></p>
 * <ul>
 *     <li>Связан с {@link Session} через поле {@code sessionId}.</li>
 *     <li>Использует {@link OfferStatus} для отслеживания текущего состояния.</li>
 *     <li>Может передаваться в сервисы генерации PDF и в контроллеры для выдачи
 *         документа клиенту.</li>
 * </ul>
 *
 * <p><b>Примечание:</b></p>
 * Поле {@code pdfData} может быть {@code null}, если PDF ещё не сгенерирован.
 * Перед использованием файла необходимо проверять статус оффера.
 *
 * @author Axine
 * @since 1.0.0
 * @see OfferStatus
 * @see Session
 */
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class Offer {

    /**
     * Внутренний идентификатор оффера (UUID).
     * <p>
     * Уникальный идентификатор, присваиваемый при создании коммерческого предложения.
     * Используется для поиска, обновления и ссылок из других сущностей.
     * </p>
     */
    private UUID id;

    /**
     * Внутренний идентификатор сессии, к которой привязан оффер.
     * <p>
     * Указывает на диалоговую сессию, в рамках которой было сформировано
     * коммерческое предложение. Позволяет восстановить контекст общения
     * с клиентом.
     * </p>
     */
    private UUID sessionId;

    /**
     * ID квартиры, для которой построено КП.
     * <p>
     * Ссылается на конкретный объект недвижимости, выбранный пользователем
     * или предложенный ассистентом. Используется для получения детальной
     * информации о квартире при формировании предложения.
     * </p>
     */
    private Long apartmentId;

    /**
     * Текст коммерческого предложения (заполненный шаблон).
     * <p>
     * Содержит человекочитаемое описание предложения: параметры квартиры,
     * условия, стоимость и другую информацию, сгенерированную на основе
     * данных сессии и выбранного объекта.
     * </p>
     */
    private String offerText;

    /**
     * PDF-файл коммерческого предложения.
     * <p>
     * Байтовый массив, содержащий сгенерированный PDF-документ. Может быть
     * {@code null}, если PDF ещё не создан (статус {@link OfferStatus#NEW}).
     * После успешной генерации заполняется и статус переводится в
     * {@link OfferStatus#READY}.
     * </p>
     */
    private byte[] pdfData;

    /**
     * Время создания оффера.
     * <p>
     * Дата и время формирования коммерческого предложения. Используется
     * для сортировки, анализа давности и логирования. Рекомендуется
     * устанавливать при создании (например, {@code LocalDateTime.now()}).
     * </p>
     */
    private LocalDateTime createdAt;

    /**
     * Статус оффера.
     * <p>
     * Определяет текущее состояние коммерческого предложения в его жизненном
     * цикле. Принимает значения из перечисления {@link OfferStatus}.
     * Управляет доступностью PDF-файла и возможностью использования оффера
     * в дальнейшем.
     * </p>
     *
     * @see OfferStatus
     */
    private OfferStatus status;
}