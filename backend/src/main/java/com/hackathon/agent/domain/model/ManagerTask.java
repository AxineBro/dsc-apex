package com.hackathon.agent.domain.model;

import com.hackathon.agent.application.dto.SessionData;
import com.hackathon.agent.infrastructure.ai.tools.GigaChatTools;
import lombok.Builder;
import lombok.Data;

import java.time.LocalDateTime;
import java.util.UUID;

/**
 * Модель данных, представляющая задачу (тикет) для передачи диалога менеджеру.
 * <p>
 * Используется в сценариях, когда AI-ассистент не может обработать запрос пользователя
 * (например, недостаточно данных, ошибка, превышение лимитов) и требуется вмешательство
 * специалиста. Задача содержит всю необходимую информацию для менеджера:
 * идентификатор сессии, контакт клиента, причину перевода, выбранную квартиру,
 * историю диалога и текущий статус обработки.
 * </p>
 *
 * <p><b>Назначение:</b></p>
 * <ul>
 *     <li>Инкапсуляция данных для эскалации запроса к менеджеру.</li>
 *     <li>Хранение в базе данных или очереди для последующей обработки.</li>
 *     <li>Отслеживание статуса задачи (создана, в работе, завершена).</li>
 * </ul>
 *
 * <p><b>Использование:</b></p>
 * <pre>
 * // Создание задачи при ошибке в AgentOrchestrator
 * ManagerTask task = ManagerTask.builder()
 *         .sessionId(session.getId())
 *         .clientPhone(session.getClientPhone())
 *         .reason("error_NullPointerException")
 *         .selectedApartmentId(session.getSelectedApartmentId())
 *         .dialogHistory(session.getDialogHistoryAsString())
 *         .status("NEW")
 *         .createdAt(LocalDateTime.now())
 *         .build();
 *
 * // Сохранение в репозиторий или отправка в очередь
 * managerTaskService.create(task);
 * </pre>
 *
 * <p><b>Жизненный цикл:</b></p>
 * Задача создаётся с начальным статусом (например, {@code NEW} или {@code CREATED}),
 * затем менеджер может взять её в работу (статус {@code IN_PROGRESS}) и завершить
 * ({@code COMPLETED} или {@code CLOSED}). Возможны и другие статусы в зависимости
 * от бизнес-процесса.
 *
 * <p><b>Примечания по полям:</b></p>
 * <ul>
 *     <li>{@code dialogHistory} может хранить полную историю сообщений в формате JSON
 *         или строковом представлении для восстановления контекста.</li>
 *     <li>{@code selectedApartmentId} может быть {@code null}, если клиент ещё не выбрал
 *         квартиру, но требуется помощь менеджера.</li>
 *     <li>{@code status} — рекомендуется использовать перечисление (enum) для строгой
 *         типизации, но в текущей реализации это строка.</li>
 * </ul>
 *
 * @author Axine
 * @since 1.0.0
 * @see GigaChatTools#transferToManager
 */
@Data
@Builder
public class ManagerTask {

    /**
     * Уникальный внутренний идентификатор задачи (первичный ключ).
     * <p>
     * Генерируется автоматически при сохранении в БД. Используется для ссылок
     * на задачу в журналах и при обновлении статуса.
     * </p>
     */
    private Long id;

    /**
     * Идентификатор сессии чата, из которой была передана задача.
     * <p>
     * Соответствует {@code sessionKey} или {@code sessionId} из {@link SessionData}.
     * Позволяет связать задачу с конкретным диалогом и восстановить его при необходимости.
     * </p>
     *
     * @see SessionData#getSessionKey()
     */
    private UUID sessionId;

    /**
     * Номер телефона клиента (контактные данные).
     * <p>
     * Используется менеджером для связи с клиентом. Может быть получен из сессии
     * или от пользователя в процессе диалога.
     * </p>
     */
    private String clientPhone;

    /**
     * Причина перевода задачи менеджеру.
     * <p>
     * Может содержать код ошибки (например, {@code "error_NullPointerException"}),
     * описание проблемы ({@code "Не удалось подобрать варианты"}) или категорию
     * ({@code "Нужна консультация"}). Используется для классификации и приоритизации.
     * </p>
     */
    private String reason;

    /**
     * Идентификатор квартиры, которую пользователь выбрал в процессе диалога
     * (если применимо).
     * <p>
     * Может быть {@code null}, если выбор ещё не сделан или не требуется.
     * Используется менеджером для уточнения деталей по конкретному объекту.
     * </p>
     */
    private Long selectedApartmentId;

    /**
     * История диалога в виде строки (обычно JSON или форматированный текст).
     * <p>
     * Содержит все сообщения между пользователем и ассистентом для полного
     * восстановления контекста. Может использоваться менеджером для понимания
     * ситуации без повторного опроса клиента.
     * </p>
     */
    private String dialogHistory;

    /**
     * Текущий статус обработки задачи.
     * <p>
     * Рекомендуемые значения (зависят от бизнес-процесса):
     * <ul>
     *     <li>{@code NEW} — создана, ожидает обработки.</li>
     *     <li>{@code IN_PROGRESS} — менеджер взял в работу.</li>
     *     <li>{@code COMPLETED} — задача решена, клиент проконсультирован.</li>
     *     <li>{@code CANCELLED} — отменена (например, клиент отписался).</li>
     * </ul>
     * Для улучшения типобезопасности рекомендуется заменить на {@code enum}.
     * </p>
     */
    private String status;

    /**
     * Дата и время создания задачи.
     * <p>
     * Устанавливается при инициализации (обычно {@code LocalDateTime.now()}).
     * Используется для мониторинга времени обработки (SLA) и сортировки задач.
     * </p>
     */
    private LocalDateTime createdAt;
}